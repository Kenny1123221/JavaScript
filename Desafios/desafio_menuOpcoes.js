// Menu de opções utilizando switch

let opcao = 1;

switch (opcao) {
    case 1:
        console.log("Iniciar jogo")
        break;
    case 2:
        console.log("Carregar jogo")
        break;
    case 3:
        console.log("Ver configurações")
        break;
    case 4:
        console.log("Sair do jogo")
        break;
    default:
        console.log("Opção inválida!")
        break;
}